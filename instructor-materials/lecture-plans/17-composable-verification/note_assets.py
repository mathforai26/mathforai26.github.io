"""Typeset exact query text and measured example sizes for the companion."""

from query_text import PROMPT, STATEMENT_PROMPT


def tex_escape(text):
    escapes = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$',
               '#': r'\#', '_': r'\_', '{': r'\{', '}': r'\}',
               '~': r'\textasciitilde{}', '^': r'\textasciicircum{}',
               '`': r'\textasciigrave{}'}
    return ''.join(escapes.get(c, c) for c in text)


def tex_text(text):
    """Preserve characters and line boundaries; TeX adds visual line wrapping."""
    lines = [tex_escape(line) + r'\par' if line else r'\smallskip' for line in text.split('\n')]
    return ('% Generated by examples.py; do not edit.\n'
            '\\begingroup\\small\\raggedright\n'
            '\\setlength{\\parindent}{0pt}\\setlength{\\parskip}{3pt}\n'
            + '\n'.join(lines) + '\n\\endgroup\n')


def assets(queries, displays, stats, count, bound):
    result = {'generated/query-prompt.tex': tex_text(PROMPT),
              'generated/query-statement-prompt.tex': tex_text(STATEMENT_PROMPT)}
    for name, text in queries.items():
        result[f'traces/queries/{name}.txt'] = text + '\n'
    for name, text in displays.items():
        result[f'generated/{name}.tex'] = tex_text(text)
    result['generated/metrics.tex'] = (
        '% Generated by examples.py; do not edit.\n'
        f'\\newcommand{{\\VerifierQuestionCount}}{{{count}}}\n'
        f'\\newcommand{{\\VerifierBound}}{{{bound:,}}}\n'
        f'\\newcommand{{\\LongNameLength}}{{{2 * bound:,}}}\n'
        f'\\newcommand{{\\LongCodeBytes}}{{{stats["long-code-301"]["code_bytes"]:,}}}\n'
        f'\\newcommand{{\\LongCodeQueryBytes}}{{{stats["long-code-301"]["max_query_bytes"]:,}}}\n')
    rows = [('Forty desk instructions', 'desk'), ('Simple tax', 'simple-tax'),
            ('Arithmetic, three records', 'arithmetic-simple'),
            ('Arithmetic', 'arithmetic'), ('Arithmetic, alternate wording', 'arithmetic-rephrased'),
            ('Full tax, three exclusions', 'full-tax-yes'), ('Full tax, 512 exclusions', 'full-tax-512'),
            ('Full tax, one long flag name', 'full-tax-long-name'),
            ('Tax code with 301 allowances', 'long-code-301'),
            ('Cap, then deduction', 'cap-then-deduct'),
            ('Deduction, then cap', 'deduct-then-cap')]
    table = ['% Generated by examples.py; do not edit.', r'\begin{center}', r'\begin{tabular}{lrrr}',
             r'\toprule', r'Example & Input bytes & Records & Maximum query bytes\\', r'\midrule']
    for label, key in rows:
        values = stats[key]
        table.append(label + ' & ' + ' & '.join(f'{values[field]:,}' for field in
                     ('input_bytes', 'records', 'max_query_bytes')) + r'\\')
    table += [r'\bottomrule', r'\end{tabular}', r'\end{center}']
    result['generated/example-statistics.tex'] = '\n'.join(table) + '\n'
    return result
